export function labelFor(key: string): string {
  const known = labels[key];

  if (known) {
    return known;
  }

  const spaced = key
    .replace(/([a-z0-9])([A-Z])/g, "$1 $2")
    .replaceAll("-", " ")
    .replaceAll("_", " ");

  return spaced.charAt(0).toUpperCase() + spaced.slice(1);
}

export function formatContentPath(path: string): string {
  return path
    .split(".")
    .map((segment) =>
      /^\d+$/.test(segment)
        ? `Item ${Number(segment) + 1}`
        : labelFor(segment),
    )
    .join(" → ");
}
